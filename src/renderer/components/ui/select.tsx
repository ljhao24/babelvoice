import * as React from "react"
import { Select as SelectPrimitive } from "@base-ui/react/select"
import { cn } from "@/lib/utils"
import {
  ChevronDownIcon,
  CheckIcon,
  ChevronUpIcon,
  ChevronsUpDownIcon,
} from "lucide-react"

import { useOverlayLayer } from "@/hooks/useOverlayLayer"

// Direction A: the trigger is a Mac pop-up button and the popup a Mac menu
// (13px rows, checkmark leading, accent-filled highlight). With
// `alignItemWithTrigger` the chosen row opens over the trigger, as on macOS.

function Select<Value, Multiple extends boolean | undefined = false>({
  open,
  defaultOpen,
  onOpenChange,
  ...props
}: SelectPrimitive.Root.Props<Value, Multiple>) {
  // Base UI closes the menu on Esc; the layer keeps a dialog beneath and
  // "Esc stops speaking" out of that press.
  const handleOpenChange = useOverlayLayer(open, defaultOpen, onOpenChange)
  return (
    <SelectPrimitive.Root
      open={open}
      defaultOpen={defaultOpen}
      onOpenChange={handleOpenChange}
      {...props}
    />
  )
}

